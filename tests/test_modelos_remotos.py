def test_bootstrap_no_queda_listo_con_ollama_afectado(monkeypatch, tmp_path):
    runtime = tmp_path / "pluma-runtime.yaml"
    runtime.write_text("sistema: s\n", encoding="utf-8")
    monkeypatch.setattr(bootstrap, "RUNTIME_CONFIG_PATH", runtime)
    _instalar(monkeypatch, _Ollama(tags=[_LOCAL], version=(200, {"version": "0.21.2"})))
    asyncio.run(bootstrap.preparar())
    assert bootstrap.estado["fase"] == "error"
    assert bootstrap.estado["listo"] is False
    assert "0.35.0" in bootstrap.estado["mensaje"]


def test_bootstrap_queda_listo_con_ollama_corregido(monkeypatch, tmp_path):
    runtime = tmp_path / "pluma-runtime.yaml"
    runtime.write_text("sistema: s\n", encoding="utf-8")
    monkeypatch.setattr(bootstrap, "RUNTIME_CONFIG_PATH", runtime)
    _instalar(monkeypatch, _Ollama(tags=[_LOCAL], version=(200, {"version": "0.40.17"})))
    asyncio.run(bootstrap.preparar())
    assert bootstrap.estado["listo"] is True, bootstrap.estado["mensaje"]
    assert bootstrap.estado["ollama_version"] == "0.40.17"
